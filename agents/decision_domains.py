"""Exhaustive, reviewable ownership of bounded decisions (no engine mutation).

Membership means a compiler may select a prepared action, not that the action
is safe without the normal engine checks or that its prose can be generated by
a typed model. Unrepresented work retains the actor's existing route.
"""
from __future__ import annotations

from dataclasses import dataclass


@dataclass(frozen=True)
class DecisionDomain:
    name: str
    actions: frozenset[str]
    mode: str = "select"


def _domain(name: str, actions: str, mode: str = "select") -> DecisionDomain:
    return DecisionDomain(name, frozenset(actions.split()), mode)


