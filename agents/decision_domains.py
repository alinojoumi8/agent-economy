def validate_coverage(action_types: set[str]) -> None:
    """Fail closed when a newly registered command has no explicit owner."""
    if len(ACTION_DOMAIN) != sum(len(domain.actions) for domain in DOMAINS.values()):
        raise ValueError("decision domains overlap")
    if set(ACTION_DOMAIN) != set(action_types):
        raise ValueError(f"decision coverage differs: missing={sorted(set(action_types) - ACTION_DOMAIN.keys())}; "
                         f"unknown={sorted(ACTION_DOMAIN.keys() - set(action_types))}")
